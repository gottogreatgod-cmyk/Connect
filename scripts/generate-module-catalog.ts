/**
 * Generates src/data/module-catalog.ts — a server-safe, component-free copy of
 * the module catalog (metadata + variant defaults). The AI Copilot API route
 * uses this for planning; the client Studio uses the full registry with
 * components. Re-run this after changing module definitions:
 *
 *   bun scripts/generate-module-catalog.ts
 */
import { writeFileSync } from 'fs'
import { MODULES } from '@/modules/registry'

interface CatalogVariant {
  id: 'a' | 'b'
  label: string
  description: string
  defaults: Record<string, unknown>
  imageProps: string[]
}

interface CatalogModule {
  id: string
  name: string
  section: string
  tier: string
  purpose: string
  rule?: string
  variants: CatalogVariant[]
}

const catalog: CatalogModule[] = MODULES.map((definition) => ({
  id: definition.id,
  name: definition.name,
  section: definition.section,
  tier: definition.tier,
  purpose: definition.purpose,
  rule: definition.rule,
  variants: definition.variants.map((variant) => ({
    id: variant.id,
    label: variant.label,
    description: variant.description,
    defaults: variant.defaults as Record<string, unknown>,
    imageProps: variant.imageProps ?? [],
  })),
}))

// Sanity: defaults must be JSON-serialisable (they are persisted and planned over)
for (const entry of catalog) {
  for (const variant of entry.variants) {
    JSON.stringify(variant.defaults)
  }
}

const header = `// AUTO-GENERATED by scripts/generate-module-catalog.ts — do not edit by hand.
// Server-safe module catalog (no React components) used by the AI Copilot API.
import type { SectionId, Tier, VariantId } from '@/modules/types'

export interface CatalogVariant {
  id: VariantId
  label: string
  description: string
  defaults: Record<string, unknown>
  imageProps: string[]
}

export interface CatalogModule {
  id: string
  name: string
  section: SectionId
  tier: Tier
  purpose: string
  rule?: string
  variants: CatalogVariant[]
}

export const MODULE_CATALOG: CatalogModule[] = ${JSON.stringify(catalog, null, 2)}

const catalogById = new Map<string, CatalogModule>(MODULE_CATALOG.map((entry) => [entry.id, entry]))

export function getCatalogModule(id: string): CatalogModule | undefined {
  return catalogById.get(id)
}

export function getCatalogVariant(moduleId: string, variantId: VariantId): CatalogVariant | undefined {
  const entry = catalogById.get(moduleId)
  if (!entry) return undefined
  return entry.variants.find((variant) => variant.id === variantId) ?? entry.variants[0]
}
`

writeFileSync('src/data/module-catalog.ts', header)
console.log(`Wrote src/data/module-catalog.ts with ${catalog.length} modules (${catalog.length * 2} design paths)`)
